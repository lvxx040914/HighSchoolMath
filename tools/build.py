#!/usr/bin/env python3
"""Validated YAML selection to four repeatable XeLaTeX publications."""
from __future__ import annotations
import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path
import yaml
try:
    from .validate import validate
except ImportError:
    from validate import validate

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CONFIG = ROOT / 'config/monotonicity.yml'
EDITIONS = ('lecture', 'workbook', 'teacher', 'answer_key')


def load_selection(path: Path):
    errors, count = validate()
    if errors:
        raise ValueError('invalid bank: ' + '; '.join(errors))
    path = path.resolve()
    if not path.is_relative_to(ROOT) or path.suffix not in ('.yml', '.yaml'):
        raise ValueError('selection config must be YAML within repository')
    config = yaml.safe_load(path.read_text(encoding='utf8'))
    if not isinstance(config, dict):
        raise ValueError('selection must be a YAML mapping')
    ids, worked = config.get('question_ids'), config.get('worked_ids', [])
    if not isinstance(ids, list) or not isinstance(worked, list) or not ids:
        raise ValueError('question_ids must be nonempty list and worked_ids must be list')
    if not all(isinstance(x, str) and re.fullmatch(r'HSM-[A-Z]{3}-[0-9]{4}', x) for x in ids + worked):
        raise ValueError('malformed question ID')
    if len(ids + worked) != len(set(ids + worked)):
        raise ValueError('duplicate or overlapping question IDs')
    for qid in ids + worked:
        for name in ('stem.tex', 'solution.tex', 'answer.tex', 'metadata.yml'):
            if not (ROOT / 'questions' / qid / name).is_file():
                raise ValueError(f'{qid}: missing {name}')
    slug = config.get('slug', '')
    if not isinstance(slug, str) or not re.fullmatch(r'[a-z][a-z0-9_-]{1,48}', slug):
        raise ValueError('slug must be ASCII lowercase letters, digits, hyphen or underscore')
    title = config.get('title', slug)
    if not isinstance(title, str) or len(title)>120:
        raise ValueError('invalid title')
    return config, ids, worked, count


def latex_text(value):
    special = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$', '#': r'\#',
               '_': r'\_', '{': r'\{', '}': r'\}', '^': r'\textasciicircum{}', '~': r'\textasciitilde{}'}
    return ''.join(special.get(ch, ch) for ch in value)


def generate(config_path):
    conf, ids, worked, count = load_selection(config_path)
    out = ROOT / 'tex/generated'
    out.mkdir(parents=True, exist_ok=True)
    data = {
        'questions.tex': '\n'.join(r'\showquestion{' + qid + '}' for qid in ids),
        'workbook_questions.tex': '\n'.join(r'\showworkbookquestion{' + qid + '}{' + str({1:10, 2:13, 3:18, 4:24, 5:30}[yaml.safe_load((ROOT/'questions'/qid/'metadata.yml').read_text(encoding='utf8'))['difficulty']]) + '}' for qid in ids),
        'solutions.tex': '\n'.join(r'\showanswer{' + qid + '}' for qid in ids),
        'short_answers.tex': '\n'.join(r'\showshortanswer{' + qid + '}' for qid in ids),
        'selection_info.tex': r'\def\TrainingCount{' + str(len(ids)) + '}\n' + r'\def\WorkedCount{' + str(len(worked)) + '}\n' + r'\def\SelectionTitle{' + latex_text(conf['title']) + '}',
    }
    for file, text in data.items():
        (out / file).write_text('% Generated by tools/build.py; do not edit manually.\n' + text + '\n', encoding='utf8')
    print(f'Generated: {len(ids)} training, {len(worked)} worked ({count} bank records)', flush=True)
    return conf


def compile_edition(edition, slug):
    if not shutil.which('latexmk') or not shutil.which('xelatex'):
        raise RuntimeError('xelatex and latexmk must be available in PATH')
    source_edition = 'student' if edition == 'lecture' else edition
    out = ROOT / 'dist'
    out.mkdir(exist_ok=True)
    # -jobname ensures each product has separate aux/log/toc files.
    jobname = f'{slug}_{edition}'
    cmd = ['latexmk', '-xelatex', '-interaction=nonstopmode', '-halt-on-error',
           f'-jobname={jobname}', f'-outdir={out}', '-quiet', f'tex/{source_edition}.tex']
    print('Building:', edition, flush=True)
    proc = subprocess.run(cmd, cwd=ROOT, check=False)
    if proc.returncode:
        log = out / f'{jobname}.log'
        if log.is_file():
            lines = log.read_text(encoding='utf8', errors='replace').splitlines()
            errs = [n for n, line in enumerate(lines) if line.startswith('!') or 'fontspec Error' in line or 'LaTeX Error' in line]
            i = errs[0] if errs else max(0, len(lines)-30)
            print('\n'.join(lines[max(0,i-3):i+20]),file=sys.stderr)
        raise RuntimeError(f'{edition} compilation failed; see {log}')
    pdf = out / f'{jobname}.pdf'
    if not pdf.exists():
        raise RuntimeError(f'compiler reported success without producing {pdf}')
    if edition == 'lecture' and slug == 'monotonicity':
        shutil.copyfile(pdf, out/'monotonicity_student.pdf')  # legacy API
    print('Created:', pdf)
    return pdf


def main():
    p = argparse.ArgumentParser(description='Build four publications from a validated topic selection')
    p.add_argument('--config', default='config/monotonicity.yml')
    p.add_argument('--edition', choices=(*EDITIONS, 'student', 'all'), default='all')
    p.add_argument('--generate-only', action='store_true')
    args = p.parse_args()
    try:
        config_path = (ROOT/args.config).resolve()
        if config_path != DEFAULT_CONFIG.resolve() and args.edition not in ('workbook', 'answer_key') and not args.generate_only:
            raise ValueError('custom selections support standalone workbook/answer_key only; the lecture text is topic-specific')
        is_custom = (config_path != DEFAULT_CONFIG.resolve())
        generated = ROOT / 'tex/generated'
        snapshots = {f.name: f.read_bytes() for f in generated.glob('*.tex')} if is_custom and not args.generate_only else None
        conf = generate(config_path)
        if args.generate_only:
            return
        editions = EDITIONS if args.edition == 'all' else (('lecture',) if args.edition == 'student' else (args.edition,))
        try:
            for edition in editions:
                compile_edition(edition, conf['slug'])
        finally:
            # A custom worksheet must not alter committed default lecture indices.
            if snapshots is not None:
                for f in generated.glob('*.tex'):
                    if f.name not in snapshots:
                        f.unlink()
                for name, payload in snapshots.items():
                    (generated/name).write_bytes(payload)
    except (ValueError, RuntimeError, OSError, yaml.YAMLError) as exc:
        print('ERROR:', exc, file=sys.stderr)
        raise SystemExit(1)

if __name__ == '__main__':
    main()
